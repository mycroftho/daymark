const assert=require('node:assert/strict');
const {decode,encodeCSV,merge}=require('./data-transfer.js');
const sample={id:'shared-id',title:'=A1, "class"',date:'2026-10-25',time:'09:00',duration:90,notes:"First line\n第二行 🌸\n'quoted",location:'Room, 203',category:'class',priority:'high',reminder:'5',done:true,completedAt:'2026-10-25T10:31:00Z',reminderAcknowledged:true};
const csv=encodeCSV([sample]);
assert.ok(csv.includes('"\'=A1'));
const roundtrip=decode(csv,'tasks.csv')[0];
for(const key of Object.keys(sample))assert.deepEqual(roundtrip[key],sample[key],key);
assert.equal(decode(encodeCSV([{...sample,title:"'literal"}]),'tasks.csv')[0].title,"'literal");
assert.equal(decode('title,date,time\r\nSimple,2026-10-25,09:00\r\n','external.csv')[0].id,decode('title,date,time\nSimple,2026-10-25,09:00','external.csv')[0].id);
assert.throws(()=>decode('title,date,time\nBad,2026-02-30,09:00','bad.csv'),/YYYY/);
assert.throws(()=>decode('title,date,time\n"Unclosed','bad.csv'),/unclosed/);
assert.throws(()=>decode('title,date,time\n"a"x,2026-10-25,09:00','bad.csv'),/Unexpected/);
assert.throws(()=>decode(encodeCSV([sample,sample]),'duplicate.csv'),/duplicate/);
const old=decode(JSON.stringify({tasks:[{...sample,duration:undefined,endTime:'10:30'}]}),'old.json');
assert.equal(old[0].duration,90);
assert.equal(decode(encodeCSV([{...sample,duration:undefined,endTime:'10:30'}]),'old.csv')[0].duration,90,'Export preserves legacy end-time durations');
assert.equal(merge([{...sample,title:'Local'}],[roundtrip]).tasks[0].title,'Local');
const updated=merge([{...sample,title:'Local'}],[roundtrip],'update');assert.equal(updated.updated,1);assert.equal(updated.tasks[0].title,sample.title);
assert.equal(merge([],decode(csv,'tasks.csv')).added,1);
assert.equal(merge([sample],decode(csv,'tasks.csv')).skipped,1);
console.log('Passed: CSV/JSON round-trip, multiline and Unicode, formula escaping, validation, stable IDs and explicit merge policies.');
